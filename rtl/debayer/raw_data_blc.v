// raw_data_blc.v —— RAW 域黑电平校正 (Black Level Correction)
//
// 位置: 插在 debayer_top_wbg_2to1 **之前**:
//         csi_rx (rawdata_2pix)  ->  raw_data_blc  ->  debayer_top_wbg_2to1
//
// ---------------------------------------------------------------------------
// 为什么必须有这一级
//   SC431HAI2 的 RAW8 输出带黑电平基底(pedestal)。基底是传感器 + 模拟增益的
//   性质, 跨帧稳定 —— 但它只能从"画面里真有全黑区"的帧里读出来。
//
//   gamma_lut_v1 的表是纯 (k/2/255)^(1/2.2), 底部斜率极大 (lut(1)=15, lut(2)=21)。
//   20 级基底经 WB(增益 1.0) 后是 k=40 -> lut(40)=80, 于是全屏压着一层 80/255 的
//   灰 —— 就是肉眼看到的"雾"。用 RTL 那张表跑标定帧实测:
//     不减黑电平: p1=74   全帧没有任何一个像素低于 32
//     减黑电平20: p1=0    18.6% 的像素落到 32 以下
//
//   *** P_BLACK 由 20 改成 17 (2026-10-06) ***
//   20 的依据是标定帧的**全帧**直方图:
//       16:3491  17:27970  18:30637  19:56411  20:84327  21:85708 ...
//   当时把"16~20 都有大量像素"读成"基底落在 16~20, 取中值 20"。问题在于全帧
//   直方图里混着场景内容 —— 一帧没有全黑区的画面, 最暗的场景内容会被当成基底。
//   当天新抓的帧里有真正的黑区, 只取**最暗的 8% 块**再看, 直方图是
//       16:72   17:1820   18:676   19:15     (16 以下一个像素都没有)
//   16 是硬地板(基底的下边界), 17 是众数, 两者只差 1 -> 取 17。
//
//   20 比真基底高 3 级, 后果最重的是 B 通道: 它本来信号最小, 减掉偏大的常数后
//   直接归零。同一帧实测 (最暗 8% 块, 编码域):
//       减 20:  R/G/B = 25.7 / 22.1 /  0.3    <- B 整体为 0
//       减 17:  R/G/B = 38.9 / 41.7 / 13.9    <- B 回来了
//   暗部 B=0 而 R/G 还有二十几级 -> 暗处呈暗红/暗黄; 而且 R 与 G 各自的噪声经
//   gamma 底部约 15 级/线性级的斜率放大后, 成为暗处的红绿颗粒。这就是用户报的
//   "黑的地方出现红色噪点" —— 改 17 后暗部块内红点率由 0.218% 降到 0.046%。
//
//   *** 与 isp_matlab 的 P.BLACK = 20 已经不一致 ***
//   isp_build_params.m:21 还是 20, 其注释"实测该 sensor 最低 21"同样是旧帧的
//   观察(那帧大概没有全黑区)。要跑 MATLAB 定点模型与本模块的逐位对拍, 必须把
//   那边的 P.BLACK 一起改成 17 (isp_core.m:37 / verify_isp_chain.m:74 会跟着走),
//   否则两边从第一级就开始漂。
//
// *** 必须在白平衡增益之前 ***
//   WB 对 R/B 的增益是 >1 的(本帧灰世界 gR=0.79, gB=1.34)。若先乘后减,
//   基底被放大成 0.79*20 或 1.34*20, 一个常数 P_BLACK 抵不掉, 残差再被
//   gamma 的陡底放大, 症状是各通道黑电平不一样的花式灰。
//
// ---------------------------------------------------------------------------
// 组合逻辑, 不插流水级 —— 这是刻意的, 不要去"顺手"加一级寄存器
//   debayer_top_wbg_2to1.v 的文件头强调过"标志与数据的相对错拍不要动",
//   tb_debayer.v 的 SKIP_WORDS/SKIP_LINES 正是配着那个错拍标定的。
//   本模块对标志和数据一视同仁地透传、延迟 0 拍, 流水线总延迟不变,
//   现有仿真的采集窗口继续成立。8bit 比较+减法链在像素时钟下毫无压力。
//
// 数据约定: i_data/o_data = {高字节像素, 低字节像素}, 与 raw_to_rgb /
//   wb_gain_3ch 的约定一致(低字节 = 偶列)。*** 一个字的两个字节都要减 ***,
//   只减一个字节会得到半亮半暗的竖条纹。位序在这里无所谓 —— 两个字节
//   做的是同一件事, 所以上游 `{rawdata_2pix[7:0], rawdata_2pix[15:8]}`
//   那次字节交换与本模块无关。
//
// 饱和: 减到负钳 0, 与 MATLAB 的 `y = raw - BLACK; y(y<0)=0` 严格同语义。
//   判据用 > 而不是 >=: v == P_BLACK 时两者都出 0, 等价, 但 > 少一层下溢。
//
// P_BLACK = 0 即旁路(全零仍走比较器, 但结果恒等于输入)。
//
// TODO: P_BLACK 是参数, 改一次要重综合。要在线标定就把它改成端口挂到 VIO 上,
//       但注意 VIO 核是 Efinity 生成的(debug_edb_top), 加探针得在 Efinity 里
//       重新生成核, 改 RTL 改不出来。
// TODO: 新帧里量到的分通道基底几乎相同 (最暗 0.5% 块的众数: R 17.2 / G1 17.2 /
//       G2 17.2 / B 16.6, 最大只差 0.6 级), 所以单一 P_BLACK 是够用的 —— 20 时
//       看起来"B 通道被打死"不是分通道基底差造成的, 是那个共同值整体偏高 3 级,
//       而 B 的场景信号本来就最小, 于是最先被减到 0。真要分开做, 记得 RTL 与
//       isp_matlab 两边的 P.BLACK 必须一起改成向量, 否则定点对拍会漂。
/////////////////////////////////////////////////////////////////////////////

module raw_data_blc
#(
	parameter				P_DEPTH	= 8,	// 每个像素位宽
	parameter [P_DEPTH-1:0]	P_BLACK	= 17	// 黑电平标定值(RAW 码值), 0 = 旁路
)
(
	input						i_vs,
	input						i_hs,
	input						i_de,
	input						i_valid,
	input	[2*P_DEPTH-1:0]		i_data,		// {高字节像素, 低字节像素}

	output						o_vs,
	output						o_hs,
	output						o_de,
	output						o_valid,
	output	[2*P_DEPTH-1:0]		o_data
);

// 单像素: 减基底, 减到负钳 0
function [P_DEPTH-1:0] blc_pix;
	input [P_DEPTH-1:0] v;
	begin
		blc_pix = (v > P_BLACK) ? (v - P_BLACK) : {P_DEPTH{1'b0}};
	end
endfunction

// 高低两个字节各减一次。generate/for 在这里是多余的写法 —— 只有 2 个字节,
// 展开写出来反而一眼能核对"两个字节都减了"。
assign	o_data	= { blc_pix(i_data[2*P_DEPTH-1:P_DEPTH]),	// 高字节像素
					blc_pix(i_data[  P_DEPTH-1:0    ]) };	// 低字节像素

// 标志零延迟透传: 本模块不改变标志与数据的相对拍数
assign	o_vs	= i_vs;
assign	o_hs	= i_hs;
assign	o_de	= i_de;
assign	o_valid	= i_valid;

endmodule
